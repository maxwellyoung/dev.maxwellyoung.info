#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["fonttools==4.66.1", "brotli==1.2.0"]
# ///
"""Generate the site's web font files, @font-face CSS and preload URLs.

Run by hand from the repo root, then commit everything it writes:

    uv run scripts/fonts/subset.py            # write outputs
    uv run scripts/fonts/subset.py --check    # verify committed outputs are current

It is NOT part of `pnpm build`. The versions above are pinned so a rerun on the
same sources and config is byte-identical.

Inputs
  scripts/fonts/config.json    families, mode, characters, axis ranges, features
  public/fonts/*.woff2         the official font files, never modified in place

Outputs (generated, do not edit)
  src/app/fonts.css            @font-face rules, metric fallbacks, CSS variables
  src/lib/fontFiles.ts         URLs of the files that pages preload
  public/fonts/subset/*.woff2  only in "subset" mode

Modes (config.json "mode")
  "official"  Serve the official files untouched. Only the CSS and preload URLs
              are generated.
  "subset"    Cut each file down to config.json and split it into a core file
              (preloaded) and an extended file (unicode-range, loaded on
              demand). General Sans and Sentient are under the ITF Free Font
              License, whose sections 02 and 05 forbid subsetting without the
              foundry's written consent. Get that consent before switching
              this mode on and committing its output.

Config, per family (the last five keys only matter in subset mode)
  fallback          local font behind the metric-matched fallback face
  axes              range kept per variable axis; the full source range leaves
                    the variation data untouched
  weights           weights the site asks for; outlines are compared with the
                    source at each one
  features          OpenType features to keep; requiredFeatures must survive in
                    the core file
  core              characters beyond ASCII that go in the preloaded core file
  used, keepRanges  everything else to keep; it lands in the extended file

Rerun when
  - a source font file is replaced or upgraded (every mode);
  - config.json changes: mode, the core/extended split, kept characters, axis
    ranges or features;
  - subset mode only: content starts using a character the source font has but
    the kept set drops (it would fall back to the system font), CSS or a
    component asks for a weight outside a family's axis range (the browser
    would clamp or synthesise it), or an OpenType feature that is not in the
    family's feature list is turned on (it would silently do nothing).
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "scripts/fonts/config.json"
CSS_OUT = ROOT / "src/app/fonts.css"
TS_OUT = ROOT / "src/lib/fontFiles.ts"
SUBSET_DIR = ROOT / "public/fonts/subset"
HEADER = "GENERATED by scripts/fonts/subset.py from scripts/fonts/config.json. Do not edit."

# The string next/font uses to estimate average glyph width for its fallback
# face. Reproduced so the fallback metrics stay exactly what the site had.
AVG_CHARS = "aaabcdeeeefghiijklmnnoopqrrssttuvwxyz      "
FALLBACKS = {
    "Arial": {"azAvgWidth": 934.5116279069767, "unitsPerEm": 2048},
    "Times New Roman": {"azAvgWidth": 854.3953488372093, "unitsPerEm": 2048},
}


def fail(message: str) -> None:
    sys.exit(f"subset.py: {message}")


def parse_ranges(specs: list[str]) -> set[int]:
    out: set[int] = set()
    for spec in specs:
        lo, _, hi = spec.partition("-")
        out.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    return out


def unicode_range(codepoints: set[int]) -> str:
    """Exact list of the codepoints a file contains, compressed into ranges."""
    cps = sorted(codepoints)
    runs: list[tuple[int, int]] = []
    for cp in cps:
        if runs and cp == runs[-1][1] + 1:
            runs[-1] = (runs[-1][0], cp)
        else:
            runs.append((cp, cp))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in runs)


def load(data: bytes) -> TTFont:
    return TTFont(io.BytesIO(data), recalcTimestamp=False, lazy=False)


def features(font: TTFont) -> dict[str, list[str]]:
    out = {}
    for tag in ("GSUB", "GPOS"):
        if tag in font and font[tag].table.FeatureList:
            records = font[tag].table.FeatureList.FeatureRecord
            out[tag] = sorted({r.FeatureTag for r in records})
        else:
            out[tag] = []
    return out


def hinting(font: TTFont) -> str:
    tables = [t for t in ("fpgm", "prep", "cvt ", "hdmx", "VDMX", "LTSH") if t in font]
    instructed = 0
    if "glyf" in font:
        for name in font.getGlyphOrder():
            glyph = font["glyf"][name]
            if getattr(glyph, "program", None) and glyph.program.getAssembly():
                instructed += 1
    gasp = dict(font["gasp"].gaspRange) if "gasp" in font else None
    return f"tables={tables or 'none'} instructed-glyphs={instructed} gasp={gasp}"


def axes(font: TTFont) -> dict[str, tuple[float, float, float]]:
    if "fvar" not in font:
        return {}
    return {a.axisTag: (a.minValue, a.defaultValue, a.maxValue) for a in font["fvar"].axes}


def line_metrics(font: TTFont) -> dict:
    """Metrics that set line height and baseline. These must never change."""
    os2, hhea = font["OS/2"], font["hhea"]
    return {
        "unitsPerEm": font["head"].unitsPerEm,
        "hhea": (hhea.ascent, hhea.descent, hhea.lineGap),
        "typo": (os2.sTypoAscender, os2.sTypoDescender, os2.sTypoLineGap),
        "win": (os2.usWinAscent, os2.usWinDescent),
        "useTypoMetrics": os2.fsSelection & 0x80,
    }


def decoration_metrics(font: TTFont) -> dict:
    """Metrics a variable font may vary per weight through MVAR. When an axis
    default moves they are rebaked at the new default, so they are reported
    rather than enforced."""
    os2, post = font["OS/2"], font["post"]
    return {
        "underline": (post.underlinePosition, post.underlineThickness),
        "strikeout": (os2.yStrikeoutPosition, os2.yStrikeoutSize),
        "xHeight": os2.sxHeight,
        "capHeight": os2.sCapHeight,
        "caretOffset": font["hhea"].caretOffset,
    }


def fallback_metrics(font: TTFont, local_name: str) -> dict[str, str]:
    """Same arithmetic as next/font's metric-matched fallback face."""
    base = FALLBACKS[local_name]
    cmap, hmtx = font.getBestCmap(), font["hmtx"]
    upm, hhea = font["head"].unitsPerEm, font["hhea"]
    if any(ord(c) not in cmap for c in AVG_CHARS):
        fail(f"source font lacks a character needed for fallback metrics ({local_name})")
    avg = sum(hmtx[cmap[ord(c)]][0] for c in AVG_CHARS) / len(AVG_CHARS)
    size_adjust = avg / upm / (base["azAvgWidth"] / base["unitsPerEm"])
    pct = lambda v: f"{abs(v * 100):.2f}%"  # noqa: E731
    return {
        "ascent-override": pct(hhea.ascent / (upm * size_adjust)),
        "descent-override": pct(hhea.descent / (upm * size_adjust)),
        "line-gap-override": pct(hhea.lineGap / (upm * size_adjust)),
        "size-adjust": pct(size_adjust),
    }


def limit_axes(font: TTFont, wanted: dict[str, list[float]]) -> None:
    current = axes(font)
    limits = {}
    for tag, (lo, hi) in wanted.items():
        if tag not in current:
            fail(f"axis {tag} is not in the source font")
        cur_lo, cur_default, cur_hi = current[tag]
        if lo < cur_lo or hi > cur_hi:
            fail(f"axis {tag} range {lo}:{hi} is outside the source range {cur_lo}:{cur_hi}")
        if (lo, hi) == (cur_lo, cur_hi):
            continue  # full range kept: leave the variation data untouched
        if lo == hi:
            limits[tag] = lo
        else:
            limits[tag] = (lo, min(max(cur_default, lo), hi), hi)
    for tag in current:
        if tag not in wanted:
            fail(f"axis {tag} has no range in config.json")
    if limits:
        instancer.instantiateVariableFont(font, limits, inplace=True, optimize=True, updateFontNames=False)
        # fontTools quirk: the instancer drops gvar entries for glyphs left with
        # no deltas, and the subsetter then raises KeyError on them.
        if "gvar" in font:
            variations = font["gvar"].variations
            for glyph in font.getGlyphOrder():
                if glyph not in variations:
                    variations[glyph] = []


def take(source: TTFont, data: bytes, codepoints: set[int], family: dict) -> TTFont:
    """A fresh copy of the source, axis-limited then subset to `codepoints`."""
    font = load(data)
    limit_axes(font, family["axes"])
    options = subset.Options()
    options.layout_features = list(family["features"])
    options.layout_scripts = ["*"]
    options.hinting = False
    options.desubroutinize = True
    # Quirk: dropping glyph names (post format 3) saves about 1 KB per file but
    # makes Chrome on macOS rasterise every glyph visibly heavier. Keep them.
    options.glyph_names = True
    options.notdef_outline = True
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 7, 11, 13, 14, 16, 17, 25]
    options.name_languages = ["*"]
    options.harfbuzz_repacker = False
    options.recalc_timestamp = False
    options.prune_unicode_ranges = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted(codepoints))
    subsetter.subset(font)
    if "gasp" in source and "gasp" not in font:
        font["gasp"] = source["gasp"]  # rasteriser flags, not hint programs
    return font


def outline(glyphset, name: str):
    pen = DecomposingRecordingPen(glyphset)  # flatten composites to points
    glyphset[name].draw(pen)
    return pen.value, glyphset[name].width


def max_deviation(source: TTFont, piece: TTFont, weights: list[float]) -> float:
    """Largest outline or advance difference (font units) between the source and
    a subset, over every glyph the subset keeps, at each weight the site uses."""
    worst = 0.0
    names = [n for n in piece.getGlyphOrder() if n in set(source.getGlyphOrder())]
    for weight in weights:
        loc = {"wght": weight} if "fvar" in source else {}
        a, b = source.getGlyphSet(location=loc), piece.getGlyphSet(location=loc)
        for name in names:
            (ops_a, adv_a), (ops_b, adv_b) = outline(a, name), outline(b, name)
            worst = max(worst, abs(adv_a - adv_b))
            if [op for op, _ in ops_a] != [op for op, _ in ops_b]:
                fail(f"outline structure of {name} changed at wght {weight}")
            for (_, pts_a), (_, pts_b) in zip(ops_a, ops_b):
                for pa, pb in zip(pts_a, pts_b):
                    if pa is None or pb is None:
                        continue
                    worst = max(worst, abs(pa[0] - pb[0]), abs(pa[1] - pb[1]))
    return worst


BOUNDS = {
    "head": ("xMin", "yMin", "xMax", "yMax"),
    "hhea": ("advanceWidthMax", "minLeftSideBearing", "minRightSideBearing", "xMaxExtent"),
}


def save(font: TTFont, source: TTFont) -> bytes:
    """Compile to woff2, keeping the source's font-wide bounding box.

    Quirk: fontTools recalculates the font bounding box from the glyphs that
    are left, and a smaller box shifts anti-aliasing in Chrome on macOS by a
    grey level on a few pixels. Per-glyph boxes are still recalculated; only
    the font-wide values are put back, in a second pass that does not
    recalculate anything."""
    font.flavor = "woff2"
    first = io.BytesIO()
    font.save(first)
    again = TTFont(io.BytesIO(first.getvalue()), recalcBBoxes=False, recalcTimestamp=False, lazy=False)
    for table, fields in BOUNDS.items():
        for field in fields:
            setattr(again[table], field, getattr(source[table], field))
    again.flavor = "woff2"
    buf = io.BytesIO()
    again.save(buf)
    return buf.getvalue()


def report(label: str, data: bytes, font: TTFont) -> None:
    cmap = set(font.getBestCmap())
    feats = features(font)
    ax = {t: f"{lo:g}:{d:g}:{hi:g}" for t, (lo, d, hi) in axes(font).items()}
    print(f"  {label}")
    print(f"    {len(data)} bytes, {font['maxp'].numGlyphs} glyphs, {len(cmap)} characters, axes {ax}")
    print(f"    GSUB {' '.join(feats['GSUB']) or '-'} | GPOS {' '.join(feats['GPOS']) or '-'}")
    print(f"    hinting {hinting(font)}")
    print(f"    cmap {unicode_range(cmap)}")


def build(config: dict) -> dict[Path, bytes]:
    mode = config["mode"]
    if mode not in ("official", "subset"):
        fail(f'unknown mode "{mode}"')
    files: dict[Path, bytes] = {}
    css: list[str] = [f"/* {HEADER} */"]
    variables: list[str] = []
    preloads: dict[str, str] = {}

    for family in config["families"]:
        name = family["cssFamily"]
        print(f"{name} ({mode})")
        fallback_css = None
        for face in family["faces"]:
            src_path = ROOT / face["source"]
            data = src_path.read_bytes()
            source = load(data)
            src_cmap = set(source.getBestCmap())
            report(f"source {face['source']}", data, source)
            if face["style"] == "normal":
                fallback_css = fallback_metrics(source, family["fallback"])

            pieces: list[tuple[str, str, str | None]] = []  # (url, role, unicode-range)
            if mode == "official":
                digest = hashlib.sha256(data).hexdigest()[:8]
                url = "/" + Path(face["source"]).relative_to("public").as_posix() + f"?v={digest}"
                pieces.append((url, "core", None))
            else:
                core = {ord(c) for c in family["core"]} | set(range(0x20, 0x7F))
                used = {ord(c) for c in family["used"]}
                missing = sorted((core | used) - src_cmap)
                if missing:
                    fail(f"{face['source']} lacks configured characters: " + " ".join(f"U+{c:04X}" for c in missing))
                keep = (core | used | parse_ranges(family["keepRanges"])) & src_cmap
                keep -= {0x00, 0x0D}  # control characters are never drawn
                wanted = set(family["features"])
                src_feats = set(features(source)["GSUB"]) | set(features(source)["GPOS"])
                for role, cps in (("core", core), ("ext", keep - core)):
                    piece = take(source, data, cps, family)
                    deviation = max_deviation(source, piece, family["weights"])
                    out = save(piece, source)
                    back = load(out)  # everything below reads the bytes we ship
                    if set(back.getBestCmap()) != cps:
                        fail(f"{face['out']}-{role}: cmap does not match the requested characters")
                    got = set(features(back)["GSUB"]) | set(features(back)["GPOS"])
                    if got - wanted:
                        fail(f"{face['out']}-{role}: unexpected features {sorted(got - wanted)}")
                    # The subsetter drops a feature when none of its lookups touch
                    # a kept glyph (mark positioning without combining marks, say).
                    # The features the site's text actually exercises must survive.
                    lost = set(family["requiredFeatures"]) - got
                    if role == "core" and lost:
                        fail(f"{face['out']}-{role}: lost required features {sorted(lost)}")
                    for table, fields in BOUNDS.items():
                        if any(getattr(back[table], f) != getattr(source[table], f) for f in fields):
                            fail(f"{face['out']}-{role}: font-wide bounds in {table} changed")
                    if line_metrics(back) != line_metrics(source):
                        fail(f"{face['out']}-{role}: line metrics changed")
                    before, after = decoration_metrics(source), decoration_metrics(back)
                    moved = {k: f"{before[k]} -> {after[k]}" for k in before if before[k] != after[k]}
                    for tag, (lo, hi) in family["axes"].items():
                        got_lo, _, got_hi = axes(back).get(tag, (None, None, None))
                        if (got_lo, got_hi) != (lo, hi):
                            fail(f"{face['out']}-{role}: axis {tag} is {got_lo}:{got_hi}, expected {lo}:{hi}")
                    if not all(lo <= w <= hi for w in family["weights"] for lo, hi in [family["axes"]["wght"]]):
                        fail(f"{name}: a used weight is outside the wght range")
                    if deviation > config["maxOutlineDeviation"]:
                        fail(f"{face['out']}-{role}: outlines moved by {deviation:.3f} units")
                    digest = hashlib.sha256(out).hexdigest()[:8]
                    rel = SUBSET_DIR / f"{face['out']}-{role}.woff2"
                    files[rel] = out
                    report(f"{rel.relative_to(ROOT)}  (max outline/advance deviation {deviation:.4f} units)", out, back)
                    if moved:
                        print(f"    default-master metrics rebaked at the new axis default: {moved}")
                    url = "/" + rel.relative_to(ROOT / "public").as_posix() + f"?v={digest}"
                    pieces.append((url, role, unicode_range(set(back.getBestCmap()))))

            for url, role, urange in pieces:
                rule = [f"font-family:'{name}'", f"src:url({url}) format('woff2')",
                        f"font-display:{family['display']}", f"font-style:{face['style']}"]
                if urange:
                    rule.append(f"unicode-range:{urange}")
                css.append("@font-face{" + ";".join(rule) + "}")
                if role == "core" and face["style"] == "normal":
                    preloads[family["key"]] = url

        # The fallback face comes after every real face of the family, and the
        # family variable lists the real family first, so extended characters
        # are drawn by the real font rather than by the fallback.
        fb = [f"font-family:'{name} Fallback'", f"src:local(\"{family['fallback']}\")"]
        fb += [f"{k}:{v}" for k, v in fallback_css.items()]
        css.append("@font-face{" + ";".join(fb) + "}")
        variables.append(f"{family['variable']}:'{name}','{name} Fallback'")
        print(f"  fallback {family['fallback']} {fallback_css}")

    css.append(":root{" + ";".join(variables) + "}")
    files[CSS_OUT] = ("\n".join(css) + "\n").encode()
    ts = [f"// {HEADER}", "// URLs must match src/app/fonts.css exactly, or the browser downloads the file twice.",
          "export const fontPreloads = {"]
    ts += [f'  {key}: "{url}",' for key, url in preloads.items()]
    ts += ["} as const;", ""]
    files[TS_OUT] = "\n".join(ts).encode()
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if committed outputs differ from a fresh run")
    args = parser.parse_args()
    config = json.loads(CONFIG.read_text())
    files = build(config)
    stale = [p for p in SUBSET_DIR.glob("*.woff2") if p not in files] if SUBSET_DIR.exists() else []

    if args.check:
        wrong = [p for p, data in files.items() if not p.exists() or p.read_bytes() != data]
        if wrong or stale:
            for p in wrong + stale:
                print(f"out of date: {p.relative_to(ROOT)}", file=sys.stderr)
            sys.exit(1)
        print("font outputs are current")
        return

    for p in stale:
        p.unlink()
    for p, data in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
        print(f"wrote {p.relative_to(ROOT)} ({len(data)} bytes)")
    if SUBSET_DIR.exists() and not any(SUBSET_DIR.iterdir()):
        SUBSET_DIR.rmdir()


if __name__ == "__main__":
    main()
